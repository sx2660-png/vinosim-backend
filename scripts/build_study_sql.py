"""Build sql/008_study_links.sql from data/study_articles.json.

The JSON holds the Study articles that cover every level question and the
question -> article mapping. Run: python scripts/build_study_sql.py
"""
from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
data = json.loads((ROOT / "data" / "study_articles.json").read_text())


def q(s: str) -> str:
    return "'" + s.replace("'", "''") + "'"


def arr(xs: list[str]) -> str:
    return "ARRAY[" + ", ".join(q(x) for x in xs) + "]::text[]"


out = [
    "-- Study articles that cover every level question, and the link from each question",
    "-- to the article that explains it. Generated by scripts/build_study_sql.py from",
    "-- data/study_articles.json. Safe to run more than once.",
    "",
    "ALTER TABLE articles ADD COLUMN IF NOT EXISTS slug TEXT;",
    "CREATE UNIQUE INDEX IF NOT EXISTS articles_slug_key ON articles (slug);",
    "ALTER TABLE quiz_questions ADD COLUMN IF NOT EXISTS study_slug TEXT;",
    "",
]
for a in data["articles"]:
    if a.get("existing_title"):
        out.append(
            f"UPDATE articles SET slug = {q(a['slug'])}, category = {q(a['category'])}, "
            f"topics = {arr(a['topics'])}, content = {q(a['content'])} "
            f"WHERE title = {q(a['existing_title'])} AND (slug IS NULL OR slug = {q(a['slug'])});"
        )
    else:
        out.append(
            "INSERT INTO articles (slug, title, category, topics, content) VALUES "
            f"({q(a['slug'])}, {q(a['title'])}, {q(a['category'])}, {arr(a['topics'])}, {q(a['content'])}) "
            "ON CONFLICT (slug) DO UPDATE SET title = EXCLUDED.title, category = EXCLUDED.category, "
            "topics = EXCLUDED.topics, content = EXCLUDED.content;"
        )
out.append("")
for m in data["mapping"]:
    out.append(f"UPDATE quiz_questions SET study_slug = {q(m['slug'])} WHERE question = {q(m['question'])};")
(ROOT / "sql" / "008_study_links.sql").write_text("\n".join(out) + "\n")
print(f"{len(data['articles'])} articles, {len(data['mapping'])} question links")
